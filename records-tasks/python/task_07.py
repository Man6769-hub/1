# Задача 7. Области
regions = [
    {
        "Название": "Лесная область", "Областной центр": "Березовск",
        "Население": 740000, "Площадь": 38200, "Губернатор": "Смирнова А. В.",
    },
    {
        "Название": "Речная область", "Областной центр": "Исток",
        "Население": 1240000, "Площадь": 51700, "Губернатор": "Крылов М. П.",
    },
]

print("\n" + "=" * 45)
print("Области с населением меньше 1 млн жителей:")
print("=" * 45)
for region in regions:
    if region["Население"] < 1000000:
        for name, value in region.items():
            print(f"  {name}: {value}")
        print("-" * 45)