# Задача 3. Международные компании
companies = [{
    "Название": "Пример", "Сайт": "https://example.com", "Адрес главного офиса": "Москва, Россия",
    "Лет на мировом рынке": 25, "Сотрудники": 12000, "Филиалы в Европе": 30,
}]

print("\n" + "=" * 45)
print("Компании, в которых больше 10000 сотрудников:")
print("=" * 45)
for company in companies:
    if company["Сотрудники"] > 10000:
        for name, value in company.items():
            print(f"  {name}: {value}")
        print("-" * 45)