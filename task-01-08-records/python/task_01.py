# Задача 1. Футболисты
players = [{
    "Фамилия": "Иванов", "Имя": "Иван", "Отчество": "Иванович",
    "Пол": "мужской", "Национальность": "русский", "Рост": 185, "Вес": 80,
    "Дата рождения": "2000-05-12", "Телефон": "+70000000000", "Команда": "Динамо",
    "Номер в команде": 10, "Амплуа": "нападающий", "Голы": 12, "Игры": 63,
}]

print("\n" + "=" * 45)
print("Футболисты, сыгравшие больше 50 матчей:")
print("=" * 45)
for player in players:
    if player["Игры"] > 50:
        for name, value in player.items():
            print(f"  {name}: {value}")
        print("-" * 45)