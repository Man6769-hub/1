# Задача 6. Баскетболисты
players = [{
    "Фамилия": "Сидоров", "Имя": "Петр", "Отчество": "Алексеевич",
    "Пол": "мужской", "Национальность": "русский", "Рост": 198, "Вес": 90,
    "Дата рождения": "1999-02-10", "Телефон": "+70000000001", "Команда": "Спартак",
    "Номер в команде": 7, "Амплуа": "защитник", "Очки": 180, "Игры": 20,
}]

print("\n" + "=" * 45)
print("Баскетболисты, набравшие больше 150 очков:")
print("=" * 45)
for player in players:
    if player["Очки"] > 150:
        for name, value in player.items():
            print(f"  {name}: {value}")
        print("-" * 45)