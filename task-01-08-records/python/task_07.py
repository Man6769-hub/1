# Задача 7. Области
regions = [{
    "Название": "Примерная область", "Областной центр": "Примерск",
    "Население": 800000, "Площадь": 45000, "Губернатор": "Иванов И. И.",
}]

print("\n" + "=" * 45)
print("Области с населением меньше 1 млн жителей:")
print("=" * 45)
for region in regions:
    if region["Население"] < 1000000:
        for name, value in region.items():
            print(f"  {name}: {value}")
        print("-" * 45)