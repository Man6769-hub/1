# Задача 4. Зоопарки
zoos = [{
    "Название": "Городской зоопарк", "Животные": {"Уссурийский тигр": 2},
    "Адрес": "Москва, Россия", "Всего животных": 500, "Работники": 80,
}]

print("\n" + "=" * 45)
print("Зоопарки с уссурийскими тиграми:")
print("=" * 45)
for zoo in zoos:
    if zoo["Животные"].get("Уссурийский тигр", 0) > 0:
        for name, value in zoo.items():
            print(f"  {name}: {value}")
        print("-" * 45)